"""Svensson calibration on US data.

1. How often is the Fed's published fit degenerate (tau1 close to tau2)?
2. On curves generated by known parameters, does the optimiser recover them?
3. On real Treasury par yields, how close is the fit to the Fed's curve?

Run from the project root:  python scripts/run_calibration.py
Takes a few minutes (five starting points per date, tight tolerance).
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from eyc import calibration, us_data  # noqa: E402
from eyc.svensson import spot_rate  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUTPUT_DIR = ROOT / "output"

START = "2015-01-01"
TENORS = np.arange(1, 31, dtype=float)

# A fit is treated as well identified when the two time constants are far apart,
# and degenerate when they collapse onto each other.
WELL_IDENTIFIED = 3.0
DEGENERATE = 1.5

SAMPLE_PER_REGIME = 12
TREASURY_YEARS = (2024, 2025, 2026)
TREASURY_SAMPLE = 20

SEED = 0


def main() -> int:
    OUTPUT_DIR.mkdir(exist_ok=True)
    fed = us_data.gsw(START)
    times = fed[["TAU1", "TAU2"]]
    ratio = times.max(axis=1) / times.min(axis=1)
    betas = fed[["BETA2", "BETA3"]].abs().max(axis=1)

    print(
        f"Fed GSW: {len(fed)} days, "
        f"{fed.index.min().date()} to {fed.index.max().date()}\n"
    )

    print("=== 1. How often is the published fit degenerate? ===\n")
    print(
        f"tau2/tau1  median {ratio.median():.2f}, "
        f"10th percentile {ratio.quantile(0.10):.2f}"
    )
    print(f"           below {DEGENERATE}: {(ratio < DEGENERATE).mean():.1%} of days")
    print(
        f"max |beta| median {betas.median():.1f}, "
        f"90th percentile {betas.quantile(0.90):.1f}"
    )
    print(f"           above 100: {(betas > 100).mean():.1%} of days")

    worst = ratio.nsmallest(3).index
    print("\nmost degenerate published fits:")
    print(fed.loc[worst, ["BETA2", "BETA3", "TAU1", "TAU2"]].round(2).to_string())
    print(
        "\nThose betas are not a data error. They are two nearly collinear factors\n"
        "cancelling each other, and the curve they produce is perfectly ordinary.\n"
        "It is the same signature as the three anomalous ECB dates."
    )

    print("\n=== 2. Recovering known parameters from a generated curve ===\n")
    rng = np.random.default_rng(SEED)
    regimes = {
        "well identified": fed.index[ratio > WELL_IDENTIFIED],
        "degenerate": fed.index[ratio < DEGENERATE],
    }

    rows = []
    for name, dates in regimes.items():
        chosen = rng.choice(dates, min(SAMPLE_PER_REGIME, len(dates)), replace=False)
        for date in chosen:
            truth = tuple(fed.loc[date][column] for column in us_data.GSW_PARAMS)
            try:
                outcome = calibration.recovery_test(TENORS, truth)
            except (RuntimeError, ValueError):
                continue
            rows.append(
                {
                    "regime": name,
                    "date": str(date)[:10],
                    "tau_ratio": outcome["true_tau_ratio"],
                    "distinct_minima": outcome["distinct_minima"],
                    "curve_error_bp": outcome["curve_error_bp"],
                    "max_param_error": outcome["max_param_error"],
                }
            )

    recovery = pd.DataFrame(rows)
    recovery.to_csv(OUTPUT_DIR / "calibration_recovery.csv", index=False)
    print(
        recovery.groupby("regime")
        .agg(
            days=("date", "count"),
            median_curve_error_bp=("curve_error_bp", "median"),
            max_curve_error_bp=("curve_error_bp", "max"),
            median_param_error=("max_param_error", "median"),
            max_param_error=("max_param_error", "max"),
            mean_distinct_minima=("distinct_minima", "mean"),
        )
        .round(4)
        .to_string()
    )
    print(
        "\nThe curve comes back. The parameters do not. Several starting points\n"
        "reach parameter sets that differ by hundreds while reproducing the same\n"
        "curve to a thousandth of a basis point: the curve is identified, the\n"
        "parameterisation is not."
    )

    print("\n=== 3. Fitting real Treasury par yields ===\n")
    treasury = us_data.treasury_par_yields(TREASURY_YEARS)
    fed_zero = us_data.gsw_curve(fed, "SVENY")
    common = treasury.index.intersection(fed_zero.index)
    chosen = rng.choice(common, min(TREASURY_SAMPLE, len(common)), replace=False)

    rows = []
    for date in sorted(chosen):
        observed = treasury.loc[date]
        grid = np.array(
            [t for t in observed.index if t >= 0.5 and abs(t * 2 - round(t * 2)) < 1e-9]
        )
        values = observed[grid].to_numpy(dtype=float)
        try:
            outcome = calibration.fit(grid, values)
        except (RuntimeError, ValueError):
            continue

        reference = fed_zero.loc[date].dropna()
        mine = spot_rate(np.asarray(reference.index, dtype=float), *outcome["params"])
        rows.append(
            {
                "date": str(date)[:10],
                "rmse_bp": outcome["rmse_bp"],
                "distinct_minima": outcome["distinct_minima"],
                "tau_ratio": outcome["tau_ratio"],
                "max_gap_vs_gsw_bp": float(
                    np.abs(mine - reference.to_numpy()).max() * 100.0
                ),
            }
        )

    treasury_fit = pd.DataFrame(rows).set_index("date")
    treasury_fit.to_csv(OUTPUT_DIR / "calibration_treasury.csv")
    print(treasury_fit.round(3).to_string())
    print(
        f"\nfit quality:      median {treasury_fit['rmse_bp'].median():.2f} bp\n"
        f"gap to Fed curve: median {treasury_fit['max_gap_vs_gsw_bp'].median():.1f} bp"
    )
    print(
        "\nThat gap is not an error. The Fed fits individual off-the-run bond\n"
        "prices; the Treasury series is interpolated from on-the-run bid yields.\n"
        "Two different inputs and two different estimation problems, so the curves\n"
        "are close but were never going to coincide."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
